"""hanzo is a build backend for modern Python based on ninja."""

import os
from datetime import datetime
from pathlib import Path

import hanzo.ninja as _ninja
from hanzo.constants import WHEEL_FILENAME
from hanzo.rules import Rule
from hanzo.settings import (
    BuildConfig,
    load_extensions,
    parse_hanzo_settings,
    parse_project_metadata,
    parse_pyproject,
)
from hanzo.targets import CCExtensionTarget, CCLibraryTarget
from hanzo.utils import GitignoreMatcher, calculate_wheel_tag, to_snakecase
from hanzo.wheelfile import WheelWriter

__version__ = "0.1.0"


def _is_package(name: str, package_path: Path) -> bool:
    if not (package_path / name).is_dir():
        return False
    return (package_path / name / "__init__.py").exists()


def find_packages(package_path: Path) -> frozenset[str]:
    return frozenset(p.name for p in package_path.iterdir() if _is_package(p.name, package_path))


# PEP 517 hooks


def build_wheel(
    wheel_directory: str | os.PathLike[str],
    config_settings: dict[str, str | list[str]] | None = None,
    metadata_directory: str | os.PathLike[str] | None = None,
) -> str:
    metadata = parse_project_metadata()
    settings = parse_hanzo_settings()
    config = BuildConfig.from_settings(config_settings or {})
    # TODO: Maybe give an option to disable builtin features
    config.add_builtin_features(settings)

    wheel_directory = Path(wheel_directory)
    (build_dir := Path.cwd() / config.build_dir).mkdir(exist_ok=True)

    ext_modules = load_extensions(config)
    root_is_purelib = not ext_modules

    tag = calculate_wheel_tag(settings, config, root_is_purelib)

    project_name = to_snakecase(metadata.name)
    wheel_file = wheel_directory / WHEEL_FILENAME.format(
        name=project_name,
        version=metadata.version,
        tag=tag,
    )

    if not root_is_purelib:
        with open(build_dir / "build.ninja", "w") as ninjafile:
            writer = _ninja.NinjaWriter(ninjafile, width=1000)
            writer.comment(f"Generated by hanzo v{__version__}")

            ruleset: set[Rule] = set()
            cc_compilation_rules: set[str] = set()
            all: list[str] = []
            for ext in ext_modules.values():
                if settings.cc.export_compile_commands:
                    # TODO: Extend to support custom extension types
                    if isinstance(ext, CCLibraryTarget):
                        cc_compilation_rules.add(ext.rules["cc"].name)

                for rule in ext.rules.values():
                    if rule not in ruleset:
                        rule = rule.interpolate(config.cc)
                        ruleset.add(rule)
                        writer.rule(
                            rule.name,
                            rule.command,
                            description=rule.description,
                            depfile=rule.depfile,
                            deps=rule.deps,
                        )
                        writer.newline()

                for out in ext.build_outputs():
                    writer.build(**out)
                    writer.newline()

                # TODO: Find a more clever way to mark a target as default, and/or just
                # make all `cc-extension`s default.
                if isinstance(ext, CCExtensionTarget):
                    all.append(ext.libname)

            writer.build("all", "phony", all)
            writer.newline()
            writer.default("all")

        if config.clean:
            _ninja.clean(build_dir)

        if settings.cc.export_compile_commands:
            _ninja.write_compilation_database(build_dir, cc_compilation_rules)

        _ninja.build(build_dir)

    with WheelWriter(
        wheel_file, generator=f"hanzo {__version__}", root_is_purelib=root_is_purelib
    ) as wheel:
        package_path = settings.wheel.package_dir
        packages = find_packages(package_path)
        # step 1: create dist-info dir, write metadata into it.
        # TODO: Move into prepare_metadata
        wheel.write_metadata(metadata)

        matcher = GitignoreMatcher.from_gitignore()
        for file in matcher.match_files(package_path):
            rel_file = file.relative_to(package_path)
            file_pkg = rel_file.parts[0]
            if file_pkg not in packages:
                continue
            if file.suffix in settings.wheel.sources:
                wheel.write_file(rel_file, file, timestamp=datetime.now())
            elif file.suffix in settings.wheel.data:
                wheel.write_data_file(rel_file, file, timestamp=datetime.now())

        for file in build_dir.iterdir():
            # TODO: Refine this based on the expected kinds of build artifacts,
            # optimally from settings.
            # TODO: Support multiple packages.
            if file.suffix == ".so":
                (pkg,) = packages
                wheel.write_file(Path(pkg) / file.name, build_dir / file, timestamp=datetime.now())

    return wheel_file.name


